#!/usr/bin/env python3
"""Make every WSL distro reachable over ssh from this Windows machine.

Each distro gets its own port (from 2222, remembered per distro name), an sshd
listening on loopback and on the Tailscale address, this machine's public key,
and an alias `<hostname>-wsl-<distro>` in ~/.ssh/config.wsl that points at loopback.
Other devices reach the same distro through the aliases in the synced ssh config.
"""

import json
from pathlib import Path
import re
import shlex
import shutil
import socket
import subprocess
import sys

FIRST_PORT = 2222
LOOPBACK = "127.0.0.1"
SOCKET_OVERRIDE = "/etc/systemd/system/ssh.socket.d/zz-matchy-wsl.conf"
SSHD_DROPIN = "/etc/ssh/sshd_config.d/05-matchy-tailnet.conf"

PROVISION = """set -eu
USER_NAME=@USER@
KEY=@KEY@
if [ ! -x /usr/sbin/sshd ]; then
  command -v apt-get >/dev/null || { echo "openssh-server is missing and there is no apt-get"; exit 3; }
  apt-get update -qq
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq openssh-server
fi
[ -d /run/systemd/system ] || { echo "systemd is not running in this distro"; exit 4; }
HOME_DIR=$(getent passwd "$USER_NAME" | cut -d: -f6)
install -d -m 700 -o "$USER_NAME" "$HOME_DIR/.ssh"
touch "$HOME_DIR/.ssh/authorized_keys"
grep -qxF "$KEY" "$HOME_DIR/.ssh/authorized_keys" || echo "$KEY" >> "$HOME_DIR/.ssh/authorized_keys"
chown "$USER_NAME" "$HOME_DIR/.ssh/authorized_keys"
chmod 600 "$HOME_DIR/.ssh/authorized_keys"
if [ "$(systemctl is-enabled ssh.socket 2>/dev/null || true)" = enabled ]; then
  install -d /etc/systemd/system/ssh.socket.d
  cat > @SOCKET_OVERRIDE@ <<'EOF_SOCKET'
[Socket]
ListenStream=
@STREAMS@FreeBind=true
EOF_SOCKET
  systemctl daemon-reload
  systemctl restart ssh.socket
else
  install -d /etc/ssh/sshd_config.d
  cat > @SSHD_DROPIN@ <<'EOF_SSHD'
Port @PORT@
AddressFamily inet
@LISTENS@EOF_SSHD
  systemctl enable ssh
  systemctl restart ssh
fi
"""


def parse_distros(raw):
    names = [line.strip() for line in raw.decode("utf-16").splitlines()] if raw else []
    return [name for name in names if name and not name.startswith("docker-desktop")]


def assign_ports(distros, assigned):
    ports = dict(assigned)
    for distro in distros:
        if distro not in ports:
            port = FIRST_PORT
            while port in ports.values():
                port += 1
            ports[distro] = port
    return ports


def alias_names(hostname, distros):
    aliases = {}
    for distro in distros:
        base = f"{hostname.lower()}-wsl-" + re.sub(r"[^a-z0-9.]+", "-", distro.lower()).strip("-")
        alias, number = base, 2
        while alias in aliases.values():
            alias, number = f"{base}-{number}", number + 1
        aliases[distro] = alias
    return aliases


def listen_addresses(tailscale_ip, ip_output):
    owned = tailscale_ip and f"inet {tailscale_ip}/" in ip_output
    return [LOOPBACK, tailscale_ip] if owned else [LOOPBACK]


def ssh_config(entries):
    blocks = [
        f"Host {entry['alias']}\n\tHostName {LOOPBACK}\n\tPort {entry['port']}\n\tUser {entry['user']}\n"
        for entry in entries
    ]
    return "# Generated by run_after_92-setup-wsl-ssh.py; edits are overwritten.\n\n" + "\n".join(blocks)


def provision_script(port, addresses, user, key):
    replacements = {
        "@USER@": shlex.quote(user),
        "@KEY@": shlex.quote(key),
        "@SOCKET_OVERRIDE@": SOCKET_OVERRIDE,
        "@SSHD_DROPIN@": SSHD_DROPIN,
        "@STREAMS@": "".join(f"ListenStream={address}:{port}\n" for address in addresses),
        "@LISTENS@": "".join(f"ListenAddress {address}\n" for address in addresses),
        "@PORT@": str(port),
    }
    script = PROVISION
    for token, value in replacements.items():
        script = script.replace(token, value)
    return script


def run(args, **kwargs):
    return subprocess.run(args, capture_output=True, timeout=600, **kwargs)


def wsl_text(distro, *command):
    return run(["wsl", "-d", distro, "--", *command], text=True).stdout.strip()


def tailscale_address():
    if shutil.which("tailscale") is None:
        return None
    done = run(["tailscale", "ip", "-4"], text=True)
    return done.stdout.split()[0] if done.returncode == 0 and done.stdout.split() else None


def provision(distro, port, tailscale_ip, key):
    user = wsl_text(distro, "id", "-un")
    addresses = listen_addresses(tailscale_ip, wsl_text(distro, "ip", "-4", "-o", "addr", "show"))
    script = provision_script(port, addresses, user, key)
    done = run(["wsl", "-d", distro, "-u", "root", "--", "bash", "-s"], input=script.encode("utf-8"))
    if done.returncode != 0:
        output = (done.stdout + done.stderr).decode("utf-8", "replace").strip()
        print(f"wsl-ssh: {distro}: provisioning failed:", output)
        return None
    return user


def load_ports(path):
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else {}


def installed_distros():
    listing = run(["wsl", "-l", "-q"]) if shutil.which("wsl") else None
    return parse_distros(listing.stdout) if listing and listing.returncode == 0 else []


def remember_ports(home, distros):
    path = home / ".local" / "state" / "chezmoi" / "wsl-ssh-ports.json"
    ports = assign_ports(distros, load_ports(path))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(ports, indent=2) + "\n", encoding="utf-8")
    return ports


def check_alias(alias):
    done = run(["ssh", "-o", "BatchMode=yes", "-o", "ConnectTimeout=8", alias, "true"])
    print(f"wsl-ssh: {alias}: {'ok' if done.returncode == 0 else 'ssh failed'}")


def main():
    if sys.platform != "win32":
        return
    distros = installed_distros()
    if not distros:
        print("wsl-ssh: WSL not installed or has no distro, skipping")
        return
    home = Path.home()
    key_file = home / ".ssh" / "id_ed25519.pub"
    if not key_file.exists():
        print(f"wsl-ssh: {key_file} not found, skipping")
        return

    ports = remember_ports(home, distros)
    aliases = alias_names(socket.gethostname(), distros)
    tailscale_ip = tailscale_address()
    key = key_file.read_text(encoding="utf-8").strip()
    users = {distro: provision(distro, ports[distro], tailscale_ip, key) for distro in distros}
    entries = [
        {"alias": aliases[distro], "port": ports[distro], "user": user}
        for distro, user in users.items()
        if user
    ]
    (home / ".ssh" / "config.wsl").write_text(ssh_config(entries), encoding="utf-8")
    for entry in entries:
        check_alias(entry["alias"])


if __name__ == "__main__":
    main()
